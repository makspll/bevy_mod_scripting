//! C declarations of overlays: the LuaJIT `ffi.cdef` and a C header for testing against a C compiler.

use std::{collections::HashMap, fmt};

/// The C declaration of a [`FfiField`](crate::FfiField) type, built at compile time.
#[derive(Clone, Copy, Debug)]
pub struct CDecl {
    /// The C type name, e.g. `float` or `Vec3C`.
    pub name: &'static str,
    /// The `typedef` for LuaJIT's `ffi.cdef`, empty for C scalars.
    pub cdef: &'static str,
    /// The `typedef` for a C header (portable alignment via `BMS_ALIGN`) followed by `_Static_assert`s of the
    /// Rust layout, empty for C scalars.
    pub header: &'static str,
    /// The declarations of the field types, which must come first.
    pub deps: &'static [fn() -> CDecl],
}

/// Two different types share a C name.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CNameConflict(pub &'static str);

impl fmt::Display for CNameConflict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "two different overlays are named `{}` in C, rename one with `#[c_name = \"..\"]`",
            self.0
        )
    }
}

impl std::error::Error for CNameConflict {}

/// The declarations of `roots` and everything they contain, each once, dependencies first.
fn collect(roots: &[CDecl]) -> Result<Vec<CDecl>, CNameConflict> {
    fn visit(
        decl: CDecl,
        seen: &mut HashMap<&'static str, &'static str>,
        out: &mut Vec<CDecl>,
    ) -> Result<(), CNameConflict> {
        if let Some(cdef) = seen.get(decl.name) {
            return if *cdef == decl.cdef {
                Ok(())
            } else {
                Err(CNameConflict(decl.name))
            };
        }
        seen.insert(decl.name, decl.cdef);
        for dep in decl.deps {
            visit(dep(), seen, out)?;
        }
        if !decl.cdef.is_empty() {
            out.push(decl);
        }
        Ok(())
    }

    let (mut seen, mut out) = (HashMap::new(), Vec::new());
    for root in roots {
        visit(*root, &mut seen, &mut out)?;
    }
    Ok(out)
}

/// The LuaJIT `ffi.cdef` declaring `roots` and their field types.
pub fn cdef(roots: &[CDecl]) -> Result<String, CNameConflict> {
    Ok(collect(roots)?.iter().map(|d| d.cdef).collect())
}

/// A C11 header declaring `roots` and their field types, with `_Static_assert`s checking the C layout equals the Rust
/// one. Compiles with gcc, clang and MSVC (`/std:c11`).
pub fn c_header(roots: &[CDecl]) -> Result<String, CNameConflict> {
    let mut header = String::from(
        "/* Generated by bevy_mod_scripting_ffi, do not edit. */\n\
         #pragma once\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\
         #ifdef _MSC_VER\n\
         #define BMS_ALIGN(n) __declspec(align(n))\n\
         #else\n\
         #define BMS_ALIGN(n) __attribute__((aligned(n)))\n\
         #endif\n",
    );
    for decl in collect(roots)? {
        header.push('\n');
        header.push_str(decl.header);
    }
    Ok(header)
}

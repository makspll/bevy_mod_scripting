-- constructors
local timer = Timer.from_seconds(2.0, TimerMode.Once)
assert(timer:duration():as_secs() == 2.0, "from_seconds sets the duration")
assert(timer:mode() ~= nil, "mode")
assert(not pcall(Timer.from_seconds, -1.0, TimerMode.Once), "from_seconds rejects negative seconds")
local from_duration = Timer.new(Duration.from_secs(1.0), TimerMode.Repeating)
assert(from_duration:duration():as_secs() == 1.0, "new sets the duration")
from_duration:tick(2.5)
assert(from_duration:elapsed_secs() == 0.5, "new sets the mode, a repeating timer wraps around")

-- a timer running once stops at its duration
local once = Timer.from_seconds(1.0, TimerMode.Once)
once:tick(2.5)
assert(once:elapsed_secs() == 1.0, "a timer running once stops at its duration")
assert(once:times_finished_this_tick() == 1, "a timer running once finishes once")

-- ticking a timer that runs once
assert(not timer:finished(), "not finished at the start")
timer:tick(1.0)
assert(timer:elapsed_secs() == 1.0, "elapsed_secs")
assert(timer:elapsed():as_secs() == 1.0, "elapsed")
assert(timer:remaining_secs() == 1.0, "remaining_secs")
assert(timer:remaining():as_secs() == 1.0, "remaining")
assert(timer:fraction() == 0.5, "fraction")
assert(timer:fraction_remaining() == 0.5, "fraction_remaining")
assert(not timer:just_finished(), "not just finished before the end")
timer:tick(Duration.from_secs(1.0))
assert(timer:finished(), "finished once the duration has passed")
assert(timer:just_finished(), "just finished on the tick that finished it")
assert(timer:times_finished_this_tick() == 1, "times_finished_this_tick")
assert(not pcall(function() timer:tick(-1.0) end), "tick rejects negative seconds")
timer:tick(1.0)
assert(not timer:just_finished(), "not just finished on later ticks")
assert(timer:finished(), "still finished on later ticks")

-- pause, reset and almost_finish
timer:reset()
assert(not timer:finished(), "reset clears the finished state")
assert(timer:elapsed_secs() == 0.0, "reset clears the elapsed time")
timer:pause()
assert(timer:paused(), "paused")
timer:tick(1.0)
assert(timer:elapsed_secs() == 0.0, "a paused timer does not advance")
timer:unpause()
assert(not timer:paused(), "unpaused")
timer:almost_finish()
assert(timer:fraction() > 0.99, "almost_finish moves the timer to its end")

-- setters
timer:set_elapsed(Duration.from_secs(5.0))
assert(timer:elapsed_secs() == 5.0, "set_elapsed")
timer:set_duration(Duration.from_secs(20.0))
assert(timer:duration():as_secs() == 20.0, "set_duration")
timer:set_mode(TimerMode.Repeating)
timer:set_duration(Duration.from_secs(1.0))
timer:tick(2.5)
assert(timer:elapsed_secs() == 0.5, "set_mode, a repeating timer wraps around")

-- a repeating timer counts how often it finished
local repeating = Timer.new(Duration.from_secs(1.0), TimerMode.Repeating)
repeating:tick(2.5)
assert(repeating:times_finished_this_tick() == 2, "repeating timers finish once per duration")
assert(repeating:elapsed_secs() == 0.5, "repeating timers keep the time past their last finish")

-- stopwatches
local stopwatch = Stopwatch.new()
assert(stopwatch:elapsed_secs() == 0.0, "stopwatch starts at zero")
assert(not stopwatch:is_paused(), "stopwatch starts running")
stopwatch:tick(1.5)
assert(stopwatch:elapsed_secs() == 1.5, "stopwatch tick")
assert(stopwatch:elapsed():as_secs() == 1.5, "stopwatch elapsed")
stopwatch:pause()
assert(stopwatch:is_paused(), "stopwatch paused")
stopwatch:tick(1.0)
assert(stopwatch:elapsed_secs() == 1.5, "a paused stopwatch does not advance")
stopwatch:unpause()
stopwatch:tick(Duration.from_secs(0.5))
assert(stopwatch:elapsed_secs() == 2.0, "stopwatch tick with a duration")
stopwatch:set_elapsed(Duration.from_secs(3.0))
assert(stopwatch:elapsed_secs() == 3.0, "stopwatch set_elapsed")
stopwatch:reset()
assert(stopwatch:elapsed_secs() == 0.0, "stopwatch reset")
assert(not pcall(function() stopwatch:tick(-1.0) end), "stopwatch tick rejects negative seconds")

-- enum values compare equal to their variant, both ways
local mode_timer = Timer.from_seconds(1.0, TimerMode.Repeating)
assert(mode_timer:mode() == TimerMode.Repeating, "value == variant")
assert(TimerMode.Repeating == mode_timer:mode(), "variant == value")
assert(mode_timer:mode() ~= TimerMode.Once, "value ~= other variant")
